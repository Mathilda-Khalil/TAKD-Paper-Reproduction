    ("CNN", "CIFAR-10",  "cifar10",  "plane2",  f"{base}/cnn_cifar10_nokd_plane2_best.pth.tar",   f"{base}/cnn_cifar10_blkd_plane2_best.pth.tar",   f"{base}/cnn_cifar10_takd_plane2_best.pth.tar"),
