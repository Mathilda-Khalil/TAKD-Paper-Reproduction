import os
import torch
import pandas as pd
from data_loader import get_cifar
from model_factory import create_cnn_model

device = "cuda" if torch.cuda.is_available() else "cpu"
base = "/content/drive/MyDrive/TAKD_models"

def evaluate(model_name, path, dataset):
    if not os.path.exists(path):
        return "MISSING"

    num_classes = 100 if dataset == "cifar100" else 10
    _, test_loader = get_cifar(num_classes)

    model = create_cnn_model(model_name, dataset, use_cuda=(device == "cuda"))
    ckpt = torch.load(path, map_location=device)
    model.load_state_dict(ckpt["model_state_dict"])
    model.eval()

    correct, total = 0, 0
    with torch.no_grad():
        for x, y in test_loader:
            x, y = x.to(device), y.to(device)
            out = model(x)
            _, pred = torch.max(out, 1)
            total += y.size(0)
            correct += (pred == y).sum().item()

    return round(100.0 * correct / total, 2)

